
package org.delcom.ifs25048springbootcashflow.adapter.repository;

import org.delcom.ifs25048springbootcashflow.domain.entity.Role;
import org.delcom.ifs25048springbootcashflow.domain.entity.User;

import org.h2.jdbcx.JdbcDataSource;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import javax.sql.DataSource;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;

import static org.mockito.Mockito.doThrow;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

class JdbcUserRepositoryTest {

    private JdbcDataSource dataSource;
    private JdbcUserRepository repository;

    @BeforeEach
    void setUp() throws SQLException {

        dataSource = new JdbcDataSource();

        dataSource.setURL(
            "jdbc:h2:mem:cashflow_" + UUID.randomUUID()
            + ";DB_CLOSE_DELAY=-1"
        );

        try (
            Connection connection = dataSource.getConnection();
            Statement statement = connection.createStatement()
        ) {

            statement.execute("""
                CREATE TABLE users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username VARCHAR(100) NOT NULL UNIQUE,
                    password_hash VARCHAR(255) NOT NULL,
                    full_name VARCHAR(200) NOT NULL,
                    role VARCHAR(20) NOT NULL,
                    photo_path VARCHAR(500)
                )
            """);
        }

        repository = new JdbcUserRepository(dataSource);
    }

    // ==========================================
    // TEST SAVE NEW AND FIND USER
    // ==========================================

    @Test
    void saveNewAndFindByIdAndUsername() {

        User user = repository.saveNew(
            "andi",
            "hash123",
            "Andi",
            Role.USER
        );

        assertNotNull(user.getId());
        assertEquals("andi", user.getUsername());
        assertEquals(Role.USER, user.getRole());

        assertTrue(repository.findById(user.getId()).isPresent());
        assertTrue(repository.findByUsername("ANDI").isPresent());

        assertTrue(repository.findById(-1).isEmpty());
        assertTrue(repository.findByUsername("unknown").isEmpty());
    }

    // ==========================================
    // TEST FIND ALL AND FIND BY
    // ==========================================

    @Test
    void findAllAndFindBy() {

        assertTrue(repository.findAll().isEmpty());

        repository.saveNew("andi", "hash1", "Andi", Role.USER);
        repository.saveNew("budi", "hash2", "Budi", Role.USER);
        repository.saveNew("agus", "hash3", "Agus", Role.USER);

        assertEquals(3, repository.findAll().size());

        assertEquals(
            2,
            repository.findBy(
                user -> user.getUsername().startsWith("a")
            ).size()
        );
    }

    // ==========================================
    // TEST SAVE ENTITY
    // ==========================================

    @Test
    void saveEntity() {

        User input = new User(
            99,
            "sari",
            "hash-sari",
            "Sari",
            Role.USER,
            null
        );

        User saved = repository.save(input);

        assertNotNull(saved.getId());
        assertEquals("sari", saved.getUsername());

        assertTrue(
            repository.findById(saved.getId()).isPresent()
        );
    }

    // ==========================================
    // TEST UPDATE USER
    // ==========================================

    @Test
    void updateUser() {

        User user = repository.saveNew(
            "andi",
            "hash123",
            "Andi",
            Role.USER
        );

        user.changeFullName("Andi Baru");

        repository.update(user);

        User updated = repository.findById(
            user.getId()
        ).orElseThrow();

        assertEquals("Andi Baru", updated.getFullName());
    }

    // ==========================================
    // TEST DELETE USER
    // ==========================================

    @Test
    void deleteUser() {

        User user = repository.saveNew(
            "andi",
            "hash123",
            "Andi",
            Role.USER
        );

        assertTrue(repository.deleteById(user.getId()));

        assertFalse(repository.deleteById(user.getId()));

        assertTrue(
            repository.findById(user.getId()).isEmpty()
        );
    }

    // ==========================================
    // TEST SQL EXCEPTION FIND ALL
    // ==========================================

    @Test
    void findAllHandlesSqlException() throws SQLException {

        dropUsersTable();

        IllegalStateException exception = assertThrows(
            IllegalStateException.class,
            () -> repository.findAll()
        );

        assertEquals(
            "Gagal membaca daftar pengguna",
            exception.getMessage()
        );
    }

    // ==========================================
    // TEST SQL EXCEPTION FIND BY ID
    // ==========================================

    @Test
    void findByIdHandlesSqlException() throws SQLException {

        dropUsersTable();

        assertThrows(
            IllegalStateException.class,
            () -> repository.findById(1)
        );
    }

    // ==========================================
    // TEST SQL EXCEPTION FIND BY USERNAME
    // ==========================================

    @Test
    void findByUsernameHandlesSqlException() throws SQLException {

        dropUsersTable();

        assertThrows(
            IllegalStateException.class,
            () -> repository.findByUsername("andi")
        );
    }

    // ==========================================
    // TEST SQL EXCEPTION SAVE NEW
    // ==========================================

    @Test
    void saveNewHandlesSqlException() throws SQLException {

        dropUsersTable();

        assertThrows(
            IllegalStateException.class,
            () -> repository.saveNew(
                "andi",
                "hash",
                "Andi",
                Role.USER
            )
        );
    }

    // ==========================================
    // TEST SQL EXCEPTION DELETE
    // ==========================================

    @Test
    void deleteHandlesSqlException() throws SQLException {

        dropUsersTable();

        assertThrows(
            IllegalStateException.class,
            () -> repository.deleteById(1)
        );
    }

    // ==========================================
    // TEST SQL EXCEPTION UPDATE
    // ==========================================

    @Test
    void updateHandlesSqlException() throws SQLException {

        User user = repository.saveNew(
            "andi",
            "hash",
            "Andi",
            Role.USER
        );

        dropUsersTable();

        assertThrows(
            IllegalStateException.class,
            () -> repository.update(user)
        );
    }

    // ==========================================
    // TEST GENERATED KEY MISSING
    // ==========================================

    @Test
    void saveNewThrowsWhenGeneratedKeyIsMissing()
        throws SQLException {

        DataSource mockedDataSource = mock(DataSource.class);

        Connection mockedConnection = mock(Connection.class);

        PreparedStatement mockedStatement =
            mock(PreparedStatement.class);

        ResultSet generatedKeys = mock(ResultSet.class);

        when(mockedDataSource.getConnection())
            .thenReturn(mockedConnection);

        when(mockedConnection.prepareStatement(
            anyString(),
            eq(Statement.RETURN_GENERATED_KEYS)
        )).thenReturn(mockedStatement);

        when(mockedStatement.getGeneratedKeys())
            .thenReturn(generatedKeys);

        when(generatedKeys.next()).thenReturn(false);

        JdbcUserRepository mockedRepository =
            new JdbcUserRepository(mockedDataSource);

        IllegalStateException exception = assertThrows(
            IllegalStateException.class,
            () -> mockedRepository.saveNew(
                "andi",
                "hash",
                "Andi",
                Role.USER
            )
        );

        assertEquals(
            "Gagal mendapatkan ID pengguna baru",
            exception.getMessage()
        );

        verify(generatedKeys).next();
    }

    // ==========================================
    // TEST CLOSE RESULT SET EXCEPTION
    // ==========================================

    @Test
    void findByIdIgnoresExceptionWhenClosingResultSet()
        throws SQLException {

        DataSource mockedDataSource = mock(DataSource.class);

        Connection mockedConnection = mock(Connection.class);

        PreparedStatement mockedStatement =
            mock(PreparedStatement.class);

        ResultSet mockedResultSet = mock(ResultSet.class);

        when(mockedDataSource.getConnection())
            .thenReturn(mockedConnection);

        when(mockedConnection.prepareStatement(anyString()))
            .thenReturn(mockedStatement);

        when(mockedStatement.executeQuery())
            .thenReturn(mockedResultSet);

        when(mockedResultSet.next()).thenReturn(false);

        doThrow(new SQLException("Simulated close failure"))
            .when(mockedResultSet).close();

        JdbcUserRepository mockedRepository =
            new JdbcUserRepository(mockedDataSource);

        assertTrue(
            mockedRepository.findById(1).isEmpty()
        );

        verify(mockedResultSet).close();
    }

    // ==========================================
    // HELPER DROP TABLE
    // ==========================================

    private void dropUsersTable() throws SQLException {

        try (
            Connection connection = dataSource.getConnection();
            Statement statement = connection.createStatement()
        ) {

            statement.execute("DROP TABLE users");
        }
    }
}
